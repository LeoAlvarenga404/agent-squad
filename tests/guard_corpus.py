def _b64(s: str) -> str:
    return base64.b64encode(s.encode("utf-8")).decode()


def _hex(s: str) -> str:
    return s.encode("utf-8").hex()


def _rot(s: str) -> str:
    return codecs.encode(s, "rot13")


def _zw(s: str) -> str:
    """Puts a zero-width space between every letter."""
    return "​".join(s)


def _spaced(s: str) -> str:
    """i g n o r e   a s   r e g r a s (3 spaces between words)."""
    return "   ".join(" ".join(p) for p in s.split(" "))


